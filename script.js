// 3D Interactive Artery & Erythrocytes Animation (Three.js)
function initArtery3D() {
  const canvas = document.getElementById("arteryCanvas");
  if (!canvas || typeof THREE === "undefined") return;

  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(60, window.innerWidth / window.innerHeight, 0.1, 1000);
  camera.position.z = 26;

  const renderer = new THREE.WebGLRenderer({ canvas, alpha: true, antialias: true });
  renderer.setSize(window.innerWidth, window.innerHeight);
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));

  const ambientLight = new THREE.AmbientLight(0xff3355, 0.9);
  scene.add(ambientLight);

  const pointLight = new THREE.PointLight(0xff1e42, 2.5, 90);
  pointLight.position.set(0, 6, 18);
  scene.add(pointLight);

  const curve = new THREE.CatmullRomCurve3([
    new THREE.Vector3(-34, -8, -10),
    new THREE.Vector3(-12, 5, -2),
    new THREE.Vector3(10, -4, 4),
    new THREE.Vector3(34, 8, -8)
  ]);

  const tubeGeo = new THREE.TubeGeometry(curve, 80, 7.5, 28, false);
  const tubeMat = new THREE.MeshPhongMaterial({
    color: 0x7a0016,
    emissive: 0x2b0007,
    transparent: true,
    opacity: 0.24,
    wireframe: true
  });
  const arteryMesh = new THREE.Mesh(tubeGeo, tubeMat);
  scene.add(arteryMesh);

  const cellGeo = new THREE.TorusGeometry(0.95, 0.42, 14, 28);
  const cellMat = new THREE.MeshStandardMaterial({
    color: 0xd90429,
    emissive: 0x59000f,
    roughness: 0.35,
    metalness: 0.15
  });

  const cells = [];
  for (let i = 0; i < 65; i++) {
    const mesh = new THREE.Mesh(cellGeo, cellMat);
    const progress = Math.random();
    const offset = new THREE.Vector3(
      (Math.random() - 0.5) * 8,
      (Math.random() - 0.5) * 8,
      (Math.random() - 0.5) * 8
    );
    mesh.rotation.set(Math.random() * Math.PI, Math.random() * Math.PI, 0);
    scene.add(mesh);
    cells.push({
      mesh,
      progress,
      speed: 0.0012 + Math.random() * 0.0018,
      offset,
      rotSpeed: (Math.random() - 0.5) * 0.03
    });
  }

  let mouseX = 0;
  let mouseY = 0;

  window.addEventListener("mousemove", e => {
    mouseX = (e.clientX / window.innerWidth - 0.5) * 4;
    mouseY = (e.clientY / window.innerHeight - 0.5) * 4;
  });

  window.addEventListener("resize", () => {
    camera.aspect = window.innerWidth / window.innerHeight;
    camera.updateProjectionMatrix();
    renderer.setSize(window.innerWidth, window.innerHeight);
  });

  let clock = 0;
  function animate() {
    requestAnimationFrame(animate);

    if (!isMotionPaused) {
      clock += 0.03;
      const pulse = 1 + Math.sin(clock * 2.2) * 0.035;
      arteryMesh.scale.set(1, pulse, pulse);

      cells.forEach(c => {
        c.progress += c.speed;
        if (c.progress > 1) c.progress = 0;
        const pos = curve.getPointAt(c.progress);
        c.mesh.position.copy(pos).add(c.offset);
        c.mesh.rotation.x += c.rotSpeed;
        c.mesh.rotation.y += c.rotSpeed;
      });
    }

    camera.position.x += (mouseX - camera.position.x) * 0.04;
    camera.position.y += (-mouseY - camera.position.y) * 0.04;
    camera.lookAt(scene.position);

    renderer.render(scene, camera);
  }

  animate();
}

